#!/usr/bin/env node
// Regenerates src/dashboard-fonts.js, the Geist and Geist Mono faces the
// dashboard page embeds. They are inlined rather than fetched because the page
// loads nothing from anywhere (see dashboardCsp in src/dashboard.js): it holds
// the proxy key, and it has to work on a machine with no route to a CDN.
//
// The inputs are the variable fonts from the `geist` npm package
// (dist/fonts/geist-sans/Geist-Variable.woff2 and
// dist/fonts/geist-mono/GeistMono-Variable.woff2, v1.7.2 at the time of
// writing), subset to the characters the page draws. The weight axis is kept
// whole, so every weight the page uses comes from the one file:
//
//   pyftsubset <in.woff2> --unicodes="<UNICODES below>" --flavor=woff2 \
//     --layout-features='*' --output-file=<out.woff2>
//
// (pyftsubset is fonttools; `uvx --from 'fonttools[woff]' pyftsubset ...`
// runs it without installing anything.) Then:
//
//   node scripts/build-dashboard-fonts.mjs <Geist.woff2> <GeistMono.woff2>
//
// A character outside the subset (a non-Latin client name, say) falls back to
// the system font named after Geist in the page's font stack.

import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

export const UNICODES = 'U+0020-007E,U+00A0-00FF,U+2011,U+2013-2014,U+2018-201D,U+2022,U+2026,U+2190-2193,U+2197,U+2212,U+2713,U+20AC';

const [sans, mono] = process.argv.slice(2);
if (!sans || !mono) {
  console.error('usage: node scripts/build-dashboard-fonts.mjs <Geist.woff2> <GeistMono.woff2>');
  process.exit(2);
}

const b64 = path => readFileSync(path).toString('base64');
const out = `// GENERATED by scripts/build-dashboard-fonts.mjs — do not edit.
//
// Geist and Geist Mono, variable (wght 100–900), subset to Latin, as base64
// woff2 for the dashboard's @font-face rules. Copyright (c) 2023 Vercel, in
// collaboration with basement.studio. Licensed under the SIL Open Font
// License, Version 1.1: see dashboard-fonts.OFL.txt beside this file.

export const GEIST_WOFF2 = '${b64(sans)}';

export const GEIST_MONO_WOFF2 = '${b64(mono)}';
`;
writeFileSync(join(import.meta.dirname, '..', 'src', 'dashboard-fonts.js'), out);
console.log(`wrote src/dashboard-fonts.js (${Math.round(out.length / 1024)} KiB)`);
