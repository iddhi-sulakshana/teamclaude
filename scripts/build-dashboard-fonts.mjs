#!/usr/bin/env node
// Regenerates src/dashboard-fonts.js, the DM Sans and DM Mono faces the
// dashboard page embeds. They are inlined rather than fetched because the page
// loads nothing from anywhere (see dashboardCsp in src/dashboard.js): it holds
// the proxy key, and it has to work on a machine with no route to a CDN.
//
// The inputs are Google Fonts' own files (github.com/google/fonts:
// ofl/dmsans/DMSans[opsz,wght].ttf, v4.004, and ofl/dmmono/DMMono-Regular.ttf,
// v1.000, at the time of writing). DM Sans is variable; its weight axis is
// narrowed to the 400–600 the page sets and its optical-size axis kept whole,
// so headings and captions each get the cut drawn for their size. Both are
// then subset to the characters the page draws:
//
//   fonttools varLib.instancer 'DMSans[opsz,wght].ttf' wght=400:600 -o DMSans.ttf
//   pyftsubset <in.ttf> --unicodes="<UNICODES below>" --flavor=woff2 \
//     --layout-features='*' --output-file=<out.woff2>
//
// (both are fonttools; `uvx --from 'fonttools[woff]' pyftsubset ...` runs it
// without installing anything.) Then:
//
//   node scripts/build-dashboard-fonts.mjs <DMSans.woff2> <DMMono.woff2>
//
// A character outside the subset (a non-Latin client name, say) falls back to
// the system font named after DM Sans in the page's font stack.

import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

export const UNICODES = 'U+0020-007E,U+00A0-00FF,U+2011,U+2013-2014,U+2018-201D,U+2022,U+2026,U+2190-2193,U+2197,U+2212,U+2713,U+20AC';

const [sans, mono] = process.argv.slice(2);
if (!sans || !mono) {
  console.error('usage: node scripts/build-dashboard-fonts.mjs <DMSans.woff2> <DMMono.woff2>');
  process.exit(2);
}

const b64 = path => readFileSync(path).toString('base64');
const out = `// GENERATED by scripts/build-dashboard-fonts.mjs — do not edit.
//
// DM Sans (variable: opsz 9–40, wght 400–600) and DM Mono (Regular), subset
// to Latin, as base64 woff2 for the dashboard's @font-face rules. Copyright
// 2014 The DM Sans Project Authors and 2020 The DM Mono Project Authors.
// Licensed under the SIL Open Font License, Version 1.1: see
// dashboard-fonts.OFL.txt beside this file.

export const DM_SANS_WOFF2 = '${b64(sans)}';

export const DM_MONO_WOFF2 = '${b64(mono)}';
`;
writeFileSync(join(import.meta.dirname, '..', 'src', 'dashboard-fonts.js'), out);
console.log(`wrote src/dashboard-fonts.js (${Math.round(out.length / 1024)} KiB)`);
